export function topicBySlug(slug: string) {
  return TOPICS.find((topic) => topic.slug === slug) ?? TOPICS[0]
}

export function peopleByName(name: string) {
  return PEOPLES.find((people) => people.name === name)
}

// Народ, регион и тема — независимые признаки материала, поэтому фильтр принимает любую их комбинацию.
export function materialsFor(peopleName: string | null, topicSlug: string | null, regionName?: string | null) {
  return MATERIALS.filter((material) =>
    (!peopleName || material.people === peopleName)
    && (!topicSlug || material.topic === topicSlug)
    && (!regionName || material.region === regionName))
}

export function countForTopic(slug: string, peopleName?: string | null, regionName?: string | null) {
  return materialsFor(peopleName ?? null, slug, regionName ?? null).length
}

